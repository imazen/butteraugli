use butteraugli::{ButteraugliParams, Img, Numerics, RGB8, butteraugli};
static DISPATCH_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
fn pair(w: usize, h: usize) -> (Vec<RGB8>, Vec<RGB8>) {
    let a: Vec<_> = (0..w * h)
        .map(|i| {
            let (x, y) = (i % w, i / w);
            let c = |c: usize| ((x * 13 + y * 17 + c * 71 + (x * y) % 29) % 256) as u8;
            RGB8::new(c(0), c(1), c(2))
        })
        .collect();
    let b = a
        .iter()
        .map(|p| RGB8::new(p.r / 8 * 8, p.g / 8 * 8, p.b / 8 * 8))
        .collect();
    (a, b)
}
#[test]
fn exact_is_bit_identical_at_all_available_simd_tiers() {
    let _dispatch_lock = DISPATCH_LOCK.lock().unwrap();
    use archmage::testing::{CompileTimePolicy, for_each_token_permutation};
    for (w, h) in [(7, 9), (16, 16), (65, 49)] {
        let (a, b) = pair(w, h);
        let params = ButteraugliParams::new()
            .with_numerics(Numerics::LibjxlExact)
            .with_compute_diffmap(true);
        let mut expected = None;
        let report = for_each_token_permutation(CompileTimePolicy::Fail, |perm| {
            let r = butteraugli(
                Img::new(a.clone(), w, h).as_ref(),
                Img::new(b.clone(), w, h).as_ref(),
                &params,
            )
            .unwrap();
            let bits = (
                r.score.to_bits(),
                r.pnorm_3.to_bits(),
                r.diffmap
                    .unwrap()
                    .buf()
                    .iter()
                    .map(|v| v.to_bits())
                    .collect::<Vec<_>>(),
            );
            // Frozen x86/scalar fingerprints also execute in cross-architecture CI.
            let (score, p3, map) = match (w, h) {
                (7, 9) => (0x3ff918c740000000, 0x3ff7ee5c8a0169f1, 0x5d82edc20f83be27),
                (16, 16) => (0x3fff1e3aa0000000, 0x3ffe78618ead8a9b, 0x9c7dabcec8620c81),
                (65, 49) => (0x4000312080000000, 0x3ffe007c790e0907, 0xbd68558e8f5e1dce),
                _ => unreachable!(),
            };
            assert_eq!(bits.0, score, "score at {perm}");
            assert_eq!(bits.1, p3, "p3 at {perm}");
            let hash = bits.2.iter().fold(0xcbf29ce484222325_u64, |h, b| {
                (h ^ u64::from(*b)).wrapping_mul(0x100000001b3)
            });
            assert_eq!(hash, map, "map at {perm}");
            if expected.is_none() {
                let hash = bits.2.iter().fold(0xcbf29ce484222325_u64, |h, b| {
                    (h ^ u64::from(*b)).wrapping_mul(0x100000001b3)
                });
                eprintln!(
                    "exact fixture {w}x{h} score={:016x} p3={:016x} map={hash:016x}",
                    bits.0, bits.1
                );
            }
            if let Some(ref expected) = expected {
                assert_eq!(&bits, expected, "tier {perm}");
            } else {
                expected = Some(bits);
            }
        });
        eprintln!("{report}");
    }
}

#[test]
fn exact_matches_pinned_cpp_oracle() {
    let _dispatch_lock = DISPATCH_LOCK.lock().unwrap();
    let params = ButteraugliParams::new().with_numerics(Numerics::LibjxlExact);
    // Generated by benchmarks/libjxl_exact_2026-10-17/oracles.py using
    // libjxl a7a9c787, 80 nits, metadata-free sRGB PNG inputs.
    for line in include_str!("data/libjxl_v012_exact.tsv").lines().skip(1) {
        let cols: Vec<_> = line.split('\t').collect();
        let w: usize = cols[0].parse().unwrap();
        let h: usize = cols[1].parse().unwrap();
        let (a, b) = pair(w, h);
        let r = butteraugli(
            Img::new(a, w, h).as_ref(),
            Img::new(b, w, h).as_ref(),
            &params,
        )
        .unwrap();
        let score: f64 = cols[2].parse().unwrap();
        let p3: f64 = cols[3].parse().unwrap();
        assert!(
            (r.score - score).abs() <= 1e-6,
            "{w}x{h} max: {} vs {score}",
            r.score
        );
        assert!(
            (r.pnorm_3 - p3).abs() <= 1e-6,
            "{w}x{h} p3: {} vs {p3}",
            r.pnorm_3
        );
    }
}

#[test]
fn exact_reference_and_strided_rgb_match_one_shot() {
    let _dispatch_lock = DISPATCH_LOCK.lock().unwrap();
    use butteraugli::{ButteraugliReference, ImgRef};
    let (w, h) = (65, 49);
    let (a, b) = pair(w, h);
    let params = ButteraugliParams::new()
        .with_numerics(Numerics::LibjxlExact)
        .with_compute_diffmap(true);
    let r = butteraugli(
        Img::new(a.clone(), w, h).as_ref(),
        Img::new(b.clone(), w, h).as_ref(),
        &params,
    )
    .unwrap();
    let mut ap = vec![RGB8::new(255, 0, 255); (w + 3) * h];
    let mut bp = ap.clone();
    for y in 0..h {
        ap[y * (w + 3)..y * (w + 3) + w].copy_from_slice(&a[y * w..(y + 1) * w]);
        bp[y * (w + 3)..y * (w + 3) + w].copy_from_slice(&b[y * w..(y + 1) * w]);
    }
    let strided = butteraugli(
        ImgRef::new_stride(&ap, w, h, w + 3),
        ImgRef::new_stride(&bp, w, h, w + 3),
        &params,
    )
    .unwrap();
    let bytes = |v: &Vec<RGB8>| v.iter().flat_map(|p| [p.r, p.g, p.b]).collect::<Vec<_>>();
    let reference = ButteraugliReference::new(&bytes(&a), w, h, params).unwrap();
    let reused = reference.compare(&bytes(&b)).unwrap();
    for other in [strided, reused] {
        assert_eq!(r.score.to_bits(), other.score.to_bits());
        assert_eq!(r.pnorm_3.to_bits(), other.pnorm_3.to_bits());
        let bits =
            |v: butteraugli::ImgVec<f32>| v.buf().iter().map(|v| v.to_bits()).collect::<Vec<_>>();
        assert_eq!(
            bits(r.diffmap.clone().unwrap()),
            bits(other.diffmap.unwrap())
        );
    }
}

#[test]
fn exact_strided_linear_and_planar_reference_agree() {
    let _dispatch_lock = DISPATCH_LOCK.lock().unwrap();
    use butteraugli::{ButteraugliReference, RGB, butteraugli_linear};
    let (width, height, stride) = (33, 35, 38);
    let (a, b) = pair(width, height);
    let linear = |pixels: Vec<RGB8>| {
        pixels
            .into_iter()
            .map(|p| {
                RGB::new(
                    f32::from(p.r) / 255.0,
                    f32::from(p.g) / 255.0,
                    f32::from(p.b) / 255.0,
                )
            })
            .collect::<Vec<_>>()
    };
    let a = linear(a);
    let b = linear(b);
    let mut ap = [
        vec![0.0; stride * height],
        vec![0.0; stride * height],
        vec![0.0; stride * height],
    ];
    let mut bp = ap.clone();
    for y in 0..height {
        for x in 0..width {
            let i = y * width + x;
            let j = y * stride + x;
            ap[0][j] = a[i].r;
            ap[1][j] = a[i].g;
            ap[2][j] = a[i].b;
            bp[0][j] = b[i].r;
            bp[1][j] = b[i].g;
            bp[2][j] = b[i].b;
        }
    }
    let params = ButteraugliParams::new()
        .with_numerics(Numerics::LibjxlExact)
        .with_compute_diffmap(true);
    let r = butteraugli_linear(
        Img::new(a, width, height).as_ref(),
        Img::new(b, width, height).as_ref(),
        &params,
    )
    .unwrap();
    let reference = ButteraugliReference::new_linear_planar(
        &ap[0], &ap[1], &ap[2], width, height, stride, params,
    )
    .unwrap();
    let p = reference
        .compare_linear_planar(&bp[0], &bp[1], &bp[2], stride)
        .unwrap();
    assert_eq!(r.score.to_bits(), p.score.to_bits());
    assert_eq!(r.pnorm_3.to_bits(), p.pnorm_3.to_bits());
    assert_eq!(
        r.diffmap
            .unwrap()
            .buf()
            .iter()
            .map(|v| v.to_bits())
            .collect::<Vec<_>>(),
        p.diffmap
            .unwrap()
            .buf()
            .iter()
            .map(|v| v.to_bits())
            .collect::<Vec<_>>()
    );
}

