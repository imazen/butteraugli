#[test]
fn exact_all_srgb_reference_ingresses_agree() {
    let _dispatch_lock = DISPATCH_LOCK.lock().unwrap();
    use butteraugli::ButteraugliReference;
    let (w, h) = (65, 257);
    let (a, b) = pair(w, h);
    let a = Img::new(a, w, h);
    let b = Img::new(b, w, h);
    let bytes = |img: &butteraugli::ImgVec<RGB8>| {
        img.buf()
            .iter()
            .flat_map(|p| [p.r, p.g, p.b])
            .collect::<Vec<_>>()
    };
    let params = ButteraugliParams::new()
        .with_numerics(Numerics::LibjxlExact)
        .with_compute_diffmap(true);
    let reference = ButteraugliReference::new(&bytes(&a), w, h, params.clone()).unwrap();
    let from_srgb = ButteraugliReference::from_srgb(a.as_ref(), params).unwrap();
    let expected = reference.compare(&bytes(&b)).unwrap();
    for candidate in [&a, &b] {
        let expected = if std::ptr::eq(candidate, &a) {
            reference.compare(&bytes(&a)).unwrap()
        } else {
            expected.clone()
        };
        assert_same(
            &expected,
            &from_srgb.compare_srgb(candidate.as_ref()).unwrap(),
        );
        assert_same(
            &expected,
            &reference.compare_srgb(candidate.as_ref()).unwrap(),
        );
        assert_same(
            &expected,
            &reference.compare_strip(&bytes(candidate), 64).unwrap(),
        );
        assert_same(
            &expected,
            &reference
                .compare_strip_srgb(candidate.as_ref(), 64)
                .unwrap(),
        );
        if std::ptr::eq(candidate, &a) {
            assert_eq!(expected.score, 0.0);
            assert_eq!(expected.pnorm_3, 0.0);
        }
    }
}

